// Partial products combined bit-by-bit via Half Adder (HA) + Carry Save Adder (CSA)
// stages, with Carry Select Adder (CSEL) stages for the upper, delay-critical bits.

module ha(a,b,sum,cout);
    input a,b;
    output sum,cout;
    assign sum=a^b;
    assign cout=a&b;
endmodule

module csa(a,b,cin,sum,cout);
    input a,b,cin;
    output sum,cout;
    assign sum = a^b^cin;
    assign cout = (a&b) | (a&cin) | (b&cin);
endmodule

module csel(a,b,cin,sum,cout);
    input a,b,cin;
    output sum,cout;
    wire sum0, cout0, sum1, cout1;
    assign sum0 = a^b;
    assign cout0 = a&b;
    assign sum1 = a^b^1'b1;
    assign cout1 = a|b;
    assign sum = cin ? sum1 : sum0;
    assign cout = cin ? cout1 : cout0;
endmodule

